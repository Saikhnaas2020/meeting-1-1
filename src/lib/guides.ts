/** Employee requests pick topics; map the first meaningful topic to a guide. */
export function typeFromTopics(topics: string[]): MeetingType {
  const map: Record<string, MeetingType> = {
    "Карьер, хөгжил": "career",
    "Ажлын гүйцэтгэл": "performance",
    "Ажлын ачаалал": "wellbeing",
    "Ажил, амьдралын тэнцвэр": "wellbeing",
    "Халамж, хангамж": "support",
    "Ажлын орчин": "support",
  }
  for (const t of topics) if (map[t]) return map[t]
  return "general"
}
